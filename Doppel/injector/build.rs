// build.rs — build-time steps for the Rust injector:
//   Embed agent.jar (101) + payload.dll (102) + doppel-hud.exe (103) +
//   doppel-core.exe (104) into the exe via embed-resource. The artifacts are
//   prepared by CI BEFORE cargo build:
//     - agent.jar       -> resources/agent.jar       (copied from the JVM job)
//     - payload.dll     -> resources/payload.dll     (built by cmake in CI)
//     - doppel-hud.exe  -> resources/doppel-hud.exe  (built by the hud job)
//     - doppel-core.exe -> resources/doppel-core.exe (built by the core-rs job)
//   resource.rs reads those IDs back out at runtime.
//
//   The core binary is the algorithm process. It is embedded here, in the
//   injector, because the injector owns that process — the game JVM only
//   connects to it (PROTECTION.md §9.4).
//
// We deliberately do NOT compile C++ inside build.rs: the MSVC environment
// (vcvars INCLUDE/LIB) is not reliably available to a bare cargo build script,
// which caused repeated cl.exe failures. C++ is built by CI's own cmake step.

use std::env;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let resources_dir = manifest.join("resources");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    let mut rc = String::new();
    rc.push_str("// Auto-generated by build.rs — embed agent.jar + payload.dll + doppel-hud.exe + doppel-core.exe\n");
    rc.push_str("#include <windows.h>\n");
    rc.push_str("#define AGENT_JAR_RCDATA 101\n");
    rc.push_str("#define PAYLOAD_DLL_RCDATA 102\n");
    rc.push_str("#define HUD_EXE_RCDATA 103\n");
    rc.push_str("#define CORE_EXE_RCDATA 104\n");

    let agent_jar = resources_dir.join("agent.jar");
    let agent_rc_path = out_dir.join("agent.jar");
    if agent_jar.exists() {
        let _ = std::fs::copy(&agent_jar, &agent_rc_path);
        rc.push_str(&format!(
            "AGENT_JAR_RCDATA RCDATA \"{}\"\n",
            agent_rc_path.to_string_lossy().replace('\\', "\\\\")
        ));
        println!("cargo:rerun-if-changed={}", agent_jar.display());
    } else {
        println!("cargo:warning=resources/agent.jar not found — exe will lack embedded agent.jar");
    }

    let payload_dll = resources_dir.join("payload.dll");
    let dll_rc_path = out_dir.join("payload.dll");
    if payload_dll.exists() {
        let _ = std::fs::copy(&payload_dll, &dll_rc_path);
        rc.push_str(&format!(
            "PAYLOAD_DLL_RCDATA RCDATA \"{}\"\n",
            dll_rc_path.to_string_lossy().replace('\\', "\\\\")
        ));
        println!("cargo:rerun-if-changed={}", payload_dll.display());
    } else {
        println!("cargo:warning=resources/payload.dll not found — exe will lack embedded payload.dll");
    }

    // Optional third resource: the external HUD overlay. Embedded when the build produced it (CI
    // copies hud/target/release/doppel-hud.exe here first, exactly like payload.dll) and skipped
    // otherwise, so the injector still builds without the overlay.
    let hud_exe = resources_dir.join("doppel-hud.exe");
    let hud_rc_path = out_dir.join("doppel-hud.exe");
    if hud_exe.exists() {
        let _ = std::fs::copy(&hud_exe, &hud_rc_path);
        rc.push_str(&format!(
            "HUD_EXE_RCDATA RCDATA \"{}\"\n",
            hud_rc_path.to_string_lossy().replace('\\', "\\\\")
        ));
        println!("cargo:rerun-if-changed={}", hud_exe.display());
    } else {
        println!("cargo:warning=resources/doppel-hud.exe not found — exe will lack the embedded HUD overlay");
    }

    // Optional fourth resource: the standalone algorithm process. CI builds
    // core-rs for Windows and copies the exe here before the injector is built.
    // Skipped when absent so a dev build without the core still links — the
    // injector then reports "no core" and the algorithm modules stay offline.
    let core_exe = resources_dir.join("doppel-core.exe");
    let core_rc_path = out_dir.join("doppel-core.exe");
    if core_exe.exists() {
        let _ = std::fs::copy(&core_exe, &core_rc_path);
        rc.push_str(&format!(
            "CORE_EXE_RCDATA RCDATA \"{}\"\n",
            core_rc_path.to_string_lossy().replace('\\', "\\\\")
        ));
        println!("cargo:rerun-if-changed={}", core_exe.display());
        println!("cargo:warning=embedded doppel-core.exe (injector owns this process)");
    } else {
        println!("cargo:warning=resources/doppel-core.exe not found — injector will NOT launch a core; JVM-side dev fallback only");
    }

    let rc_path = out_dir.join("resources.rc");    let _ = std::fs::write(&rc_path, rc);

    // embed-resource's compile() returns () — it compiles + links the .rc.
    embed_resource::compile(rc_path.to_str().unwrap(), embed_resource::NONE);
    println!("cargo:warning=embedded agent.jar + payload.dll resources");
}
